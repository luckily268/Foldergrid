module.exports=async function(win,js,root,shelf){
 const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
 const pause=ms=>new Promise(r=>setTimeout(r,ms));
 const until=async(fn,label)=>{for(let i=0;i<60;i++){if(await fn())return;await pause(70);}throw Error('等待超时：'+label);};
 const meta=()=>JSON.parse(fs.readFileSync(path.join(shelf,'grid.json'),'utf8'));
 const config=()=>JSON.parse(fs.readFileSync(path.join(root,'config.json'),'utf8'));
 await js('document.getElementById("settingsBtn").click()');
 assert.equal(await js('document.getElementById("startupToggle").disabled'),true);
 const id=meta().folders[0].id, cell=meta().folders[0];
 await js('window.fg.send('+JSON.stringify({type:'saveLayout',kind:'cell',folderId:id,position:{x:140,y:230}})+');window.fg.send({type:"refresh"})');
 await until(()=>js('parseFloat(document.querySelector(".tile-wrap").style.left)===140'),'初始位置');
 await js('document.getElementById("layoutNameInput").focus()');
 await pause(150);for(const ch of '工作布局')win.webContents.sendInputEvent({type:'char',keyCode:ch});
 await until(()=>js('document.getElementById("layoutNameInput").value === "工作布局"'),'布局名键盘输入');
 await js('document.getElementById("saveLayoutPresetBtn").click()');
 await until(()=>js('document.getElementById("layoutList").textContent.includes("工作布局")'),'保存布局');
 await js('document.getElementById("layoutLockToggle").click()');
 await until(()=>config().layoutLocked===true,'锁定持久化');
 assert.equal(await js('document.querySelector(".ws-layout-row button").disabled'),true);
 await js('window.fg.send('+JSON.stringify({type:'saveLayout',kind:'cell',folderId:id,position:{x:900,y:20}})+')');
 await pause(150);assert.equal(meta().folders[0].position.x,140,'主进程拒绝锁定期间修改');
 await js('document.getElementById("layoutLockToggle").click()');await until(()=>config().layoutLocked===false,'解锁');
 await js('window.fg.send('+JSON.stringify({type:'saveLayout',kind:'cell',folderId:id,position:{x:340,y:80}})+');window.fg.send({type:"refresh"})');
 await until(()=>meta().folders[0].position.x===340,'移动位置');
 await js('document.querySelector(".ws-layout-row button").click()');
 await until(()=>meta().folders[0].position.x===140,'恢复保存的位置');
 assert.equal(meta().folders[0].name,cell.name);assert.ok(fs.existsSync(path.join(shelf,cell.name)));
 const before=JSON.parse(fs.readFileSync(path.join(root,'layout-presets.json'),'utf8'));assert.equal(before.items.length,1);
 fs.writeFileSync(path.join(root,'../settings.png'),(await win.webContents.capturePage()).toPNG());
 await js('document.querySelector(".ws-layout-row button:last-child").click()');
 await until(()=>JSON.parse(fs.readFileSync(path.join(root,'layout-presets.json'),'utf8')).items.length===0,'删除保存布局');
 assert.ok(fs.existsSync(path.join(shelf,cell.name)),'删除布局不删除格子');
 await js('document.getElementById("workspaceClose").click()');
 console.log('设置 UI、键盘输入、布局保存/锁定/恢复/删除和文件保留验证通过');
};
