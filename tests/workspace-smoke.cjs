module.exports = async function (win, js, root, shelf) {
  const fs = require('node:fs'), path = require('node:path'), assert = require('node:assert/strict');
  const electron = require('electron'), pause = ms => new Promise(r => setTimeout(r, ms));
  const until = async (condition, label) => { for (let i = 0; i < 50; i++) { if (await condition()) return; await pause(80); } throw new Error('等待超时：' + label); };
  const meta = () => JSON.parse(fs.readFileSync(path.join(shelf, 'grid.json'), 'utf8'));
  const portal = path.join(root, '映射资料'); fs.mkdirSync(portal); fs.writeFileSync(path.join(portal, '映射报告.txt'), '外部正文');
  const originalPicker = electron.dialog.showOpenDialog, originalConfirm = electron.dialog.showMessageBox, originalOpen = electron.shell.openPath;
  let opened = '', confirmation = null;
  electron.dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [portal] });
  electron.dialog.showMessageBox = async (_win, options) => { confirmation = options; return { response: 1 }; };
  electron.shell.openPath = async file => { opened = file; return ''; };
  try {
    await js('document.getElementById("back").click();document.getElementById("portalBtn").click()');
    await until(() => meta().folders.some(f => f.kind === 'portal'), '添加映射');
    await pause(200);
    const mapped = meta().folders.find(f => f.kind === 'portal');
    await js('document.getElementById("globalSearchBtn").click()');
    await pause(200);
    for (const ch of '映射 报告') win.webContents.sendInputEvent({ type: 'char', keyCode: ch });
    await until(() => js('document.getElementById("globalSearchInput").value === "映射 报告"'), '搜索框键盘输入');
    assert.match(await js('document.getElementById("globalResults").textContent'), /映射报告.txt/);
    await pause(200);
    fs.writeFileSync(path.join(root, '../workspace-search.png'), (await win.webContents.capturePage()).toPNG());
    await js('document.querySelector(".ws-result").click()');
    await until(() => opened === path.join(portal, '映射报告.txt'), '搜索结果打开');
    await js('document.getElementById("workspaceClose").click();document.querySelector(".portal-tile").click()');
    await pause(300);
    assert.match(await js('document.getElementById("folderStatus").textContent'), /映射/);
    assert.equal(await js('document.getElementById("trashZone").hidden'), true);
    await js('document.getElementById("sortSelect").value="newest";document.getElementById("sortSelect").dispatchEvent(new Event("change"))');
    await until(() => meta().folders.find(f => f.id === mapped.id).sort === 'newest', '排序持久化');
    await js('document.getElementById("typeSelect").value="image";document.getElementById("typeSelect").dispatchEvent(new Event("change"))');
    assert.equal(await js('document.querySelectorAll(".file").length'), 0);
    await js('window.fg.send(' + JSON.stringify({ type: 'trashFile', folderId: mapped.id, path: path.join(portal, '映射报告.txt') }) + ')');
    await pause(120); assert.ok(fs.existsSync(path.join(portal, '映射报告.txt')), '映射拒绝删除请求');
    await js('document.getElementById("back").click();window.fg.send(' + JSON.stringify({ type: 'deleteCell', folderId: mapped.id }) + ')');
    await until(() => !meta().folders.some(f => f.id === mapped.id), '移除映射');
    assert.ok(fs.existsSync(path.join(portal, '映射报告.txt')));
    await js('document.getElementById("organizeBtn").click();document.getElementById("editRulesBtn").click();document.getElementById("saveRulesBtn").click()');
    await until(() => JSON.parse(fs.readFileSync(path.join(root, 'config.json'))).rules?.length > 0, '保存规则');
    const source = path.join(electron.app.getPath('desktop'), '分类验收.txt'); fs.writeFileSync(source, '分类正文');
    await js('document.querySelector("[data-page=organize]").click();document.getElementById("planBtn").click()');
    await until(() => js('!!document.getElementById("executeBtn")'), '生成分类预览');
    assert.ok(fs.existsSync(source), '预览不得移动文件');
    await js('document.getElementById("executeBtn").click()');
    await until(() => fs.existsSync(path.join(shelf, '文档', '分类验收.txt')), '执行分类');
    assert.match(confirmation.message, /移入格子/);
    await until(() => js('!document.getElementById("undoBtn").disabled'), '可撤销状态');
    await js('document.getElementById("undoBtn").click()');
    await until(() => fs.existsSync(source), '撤销分类');
    assert.equal(fs.readFileSync(source, 'utf8'), '分类正文');
    await js('document.getElementById("workspaceClose").click()');
    fs.writeFileSync(path.join(root, '../workspace-result.json'), JSON.stringify({ passed: true, checks: ['portal-add', 'global-search', 'open-result', 'portal-read-only', 'portal-remove-keeps-files', 'persist-sort', 'type-filter', 'rules-save', 'plan-without-move', 'confirm-move', 'persistent-undo'] }, null, 2));
  } finally { electron.dialog.showOpenDialog = originalPicker; electron.dialog.showMessageBox = originalConfirm; electron.shell.openPath = originalOpen; }
};
